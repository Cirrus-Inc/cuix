#!/usr/bin/env node
/**
 * Generates the US map geometry behind @cirrus/cuix/map (ported from HIVE's
 * scripts/gen-us-map.mjs, HIVE ADR-0012 §2). Run from the repo root:
 *
 *   T=$(mktemp -d) && npm i --prefix "$T" us-atlas@3.0.1 topojson-client@3.1.0 d3-geo@3.1.1 && node scripts/gen-us-map.mjs "$T"
 *
 * The three packages are loaded from the directory given as the argument, so the
 * repo's node_modules, package.json and package-lock.json are never touched.
 * Input is the pre-projected Albers files (975x610, Alaska and Hawaii included),
 * so there is no projection code here. Output goes to src/map/geo/.
 */
import { createRequire } from 'node:module'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = process.argv[2]
if (!dir) {
  console.error('usage: node scripts/gen-us-map.mjs <dir with us-atlas, topojson-client, d3-geo installed>')
  process.exit(1)
}
const require = createRequire(join(resolve(dir), 'package.json'))
const { feature } = require('topojson-client')
const { geoPath } = require('d3-geo')

// Path precision, 1 digit for both levels (ADR-0012 §2; digits(2) checked on RI, DE, DC in #106: no visible gain).
const STATE_DIGITS = 1
const COUNTY_DIGITS = 1

const COMMAND =
  'T=$(mktemp -d) && npm i --prefix "$T" us-atlas@3.0.1 topojson-client@3.1.0 d3-geo@3.1.1 && node scripts/gen-us-map.mjs "$T"'
const header = (what) =>
  `// GENERATED by scripts/gen-us-map.mjs — do not edit\n// Command: ${COMMAND}\n// Source: ${what}, US Census cartographic boundaries 2017 (public domain) via us-atlas 3.0.1 (ISC), pre-projected Albers 975x610.\n`

// FIPS -> ISO 3166-2 for the 50 states and DC.
const ISO = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC',
  '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY',
  '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT',
  '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH',
  '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT',
  '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY',
}

const round = (n) => Math.round(n * 10) / 10
const shape = (f, path, withIso) => {
  const [cx, cy] = path.centroid(f)
  const d = path(f)
  if (!d || !Number.isFinite(cx) || !Number.isFinite(cy)) throw new Error(`empty geometry for ${f.id} ${f.properties.name}`)
  const base = { fips: String(f.id).padStart(withIso ? 2 : 5, '0') }
  if (withIso) base.iso = `US-${ISO[base.fips]}`
  return { ...base, name: f.properties.name, cx: round(cx), cy: round(cy), d }
}
const byFips = (a, b) => (a.fips < b.fips ? -1 : 1)
const rows = (items) => items.map((i) => `  ${JSON.stringify(i)},`).join('\n')

const statesTopo = require('us-atlas/states-albers-10m.json')
const countiesTopo = require('us-atlas/counties-albers-10m.json')

const statePath = geoPath(null).digits(STATE_DIGITS)
const countyPath = geoPath(null).digits(COUNTY_DIGITS)

const states = feature(statesTopo, statesTopo.objects.states).features.map((f) => shape(f, statePath, true)).sort(byFips)
if (states.length !== 51) throw new Error(`expected 51 states, got ${states.length}`)
for (const s of states) if (!s.iso || s.iso.endsWith('undefined')) throw new Error(`no ISO code for ${s.fips} ${s.name}`)

const counties = feature(countiesTopo, countiesTopo.objects.counties).features.map((f) => shape(f, countyPath, false)).sort(byFips)

// us-atlas drops the Census "city" suffix, so an independent city and the county
// of the same name collide (Baltimore 24005 and 24510). Census codes these cities
// 510 and up: suffix those, then fail if any name still repeats within a state.
const seen = new Map()
for (const c of counties) {
  const key = `${c.fips.slice(0, 2)}|${c.name}`
  seen.set(key, (seen.get(key) ?? 0) + 1)
}
for (const c of counties) if (seen.get(`${c.fips.slice(0, 2)}|${c.name}`) > 1 && Number(c.fips.slice(2)) >= 510) c.name += ' city'
const names = new Set()
for (const c of counties) {
  const key = `${c.fips.slice(0, 2)}|${c.name}`
  if (names.has(key)) throw new Error(`duplicate county name ${c.name} in ${c.fips.slice(0, 2)}`)
  names.add(key)
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src/map/geo')
const countyDir = join(out, 'counties')
mkdirSync(countyDir, { recursive: true })
for (const f of readdirSync(countyDir)) if (f.endsWith('.ts')) rmSync(join(countyDir, f))

writeFileSync(
  join(out, 'usStates.ts'),
  `${header('states-albers-10m')}
export interface StateShape {
  fips: string
  iso: string
  name: string
  cx: number
  cy: number
  d: string
}

export interface CountyShape {
  fips: string
  name: string
  cx: number
  cy: number
  d: string
}

export const VIEWBOX = '0 0 975 610'

export const US_STATES: StateShape[] = [
${rows(states)}
]
`,
)

// Names and codes only, no paths: the route and the list import this, so the
// main bundle (and the phone page, which draws no map) carries no geometry.
writeFileSync(
  join(out, 'usStateIndex.ts'),
  `${header('states-albers-10m')}
export interface StateInfo {
  fips: string
  iso: string
  name: string
}

export const US_STATE_INDEX: StateInfo[] = [
${rows(states.map(({ fips, iso, name }) => ({ fips, iso, name })))}
]
`,
)

for (const s of states) {
  const list = counties.filter((c) => c.fips.startsWith(s.fips))
  if (list.length === 0) throw new Error(`no counties for ${s.iso}`)
  writeFileSync(
    join(countyDir, `${s.iso}.ts`),
    `${header('counties-albers-10m')}import type { CountyShape } from '../usStates.ts'

export const COUNTIES: CountyShape[] = [
${rows(list)}
]
`,
  )
}
// One literal import() per state, so every bundler splits one chunk per state
// without a glob plugin; UsMap uses this unless the consumer passes loadCounties.
writeFileSync(
  join(out, 'countyLoaders.ts'),
  `${header('counties-albers-10m')}import type { CountyShape } from './usStates.ts'

export const COUNTY_LOADERS: Record<string, () => Promise<{ COUNTIES: CountyShape[] }>> = {
${states.map((s) => `  '${s.iso}': () => import('./counties/${s.iso}.ts'),`).join('\n')}
}
`,
)

const orphans = counties.filter((c) => !ISO[c.fips.slice(0, 2)])
console.log(`${states.length} states, ${counties.length - orphans.length} counties, ${orphans.length} ignored (outside the 51)`)

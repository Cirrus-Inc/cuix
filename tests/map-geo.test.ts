import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { US_STATES, VIEWBOX } from '../src/map/geo/usStates.ts';
import { US_STATE_INDEX } from '../src/map/geo/usStateIndex.ts';
import { COUNTY_LOADERS } from '../src/map/geo/countyLoaders.ts';

// Ported from HIVE tests/unit/us-map-geo.test.ts: generated geometry, 51 states,
// one county file per state, never one bundle.
const GEO = new URL('../src/map/geo/', import.meta.url);
const COUNTIES = new URL('counties/', GEO);
const STATES_BUDGET = 120 * 1024;
const COUNTY_BUDGET = 60 * 1024;

type CountyMod = { COUNTIES: { fips: string; name: string; cx: number; cy: number; d: string }[] };

test('51 unique states (50 plus DC) in the shared viewbox', () => {
  assert.equal(VIEWBOX, '0 0 975 610');
  assert.equal(US_STATES.length, 51);
  assert.equal(new Set(US_STATES.map((s) => s.fips)).size, 51);
  assert.equal(new Set(US_STATES.map((s) => s.iso)).size, 51);
  for (const iso of ['US-FL', 'US-DC', 'US-RI', 'US-DE']) assert.ok(US_STATES.some((s) => s.iso === iso), iso);
  for (const s of US_STATES) {
    assert.match(s.fips, /^\d{2}$/);
    assert.match(s.iso, /^US-[A-Z]{2}$/);
    assert.ok(s.d.startsWith('M'), s.iso);
    assert.ok(Number.isFinite(s.cx) && Number.isFinite(s.cy), s.iso);
  }
  assert.deepEqual(
    US_STATE_INDEX,
    US_STATES.map(({ fips, iso, name }) => ({ fips, iso, name })),
  );
});

test('one county file and one loader per state; every county FIPS starts with its state FIPS', async () => {
  const files = readdirSync(COUNTIES).map((f) => f.replace('.ts', '')).sort();
  const isos = US_STATES.map((s) => s.iso).sort();
  assert.deepEqual(files, isos);
  assert.deepEqual(Object.keys(COUNTY_LOADERS).sort(), isos);
  let total = 0;
  for (const s of US_STATES) {
    const mod = (await import(new URL(`${s.iso}.ts`, COUNTIES).href)) as CountyMod;
    assert.ok(mod.COUNTIES.length > 0, s.iso);
    const names = new Set<string>();
    const fips = new Set<string>();
    for (const c of mod.COUNTIES) {
      assert.match(c.fips, new RegExp(`^${s.fips}\\d{3}$`), `${s.iso} ${c.name}`);
      assert.ok(c.d.startsWith('M'), `${s.iso} ${c.name}`);
      names.add(c.name);
      fips.add(c.fips);
    }
    assert.equal(fips.size, mod.COUNTIES.length, `${s.iso} fips`);
    assert.equal(names.size, mod.COUNTIES.length, `${s.iso} county names`);
    total += mod.COUNTIES.length;
  }
  assert.equal(total, 3142);
});

test('stays within the size budgets (raw bytes)', () => {
  assert.ok(statSync(new URL('usStates.ts', GEO)).size <= STATES_BUDGET, 'usStates.ts');
  for (const f of readdirSync(COUNTIES)) assert.ok(statSync(new URL(f, COUNTIES)).size <= COUNTY_BUDGET, f);
});

test('every generated file carries the GENERATED header, command and source line', () => {
  const files = ['usStates.ts', 'usStateIndex.ts', 'countyLoaders.ts', ...readdirSync(COUNTIES).map((c) => `counties/${c}`)];
  for (const f of files) {
    const lines = readFileSync(new URL(f, GEO), 'utf8').split('\n');
    assert.equal(lines[0], '// GENERATED by scripts/gen-us-map.mjs — do not edit', f);
    assert.ok(lines[1]?.includes('node scripts/gen-us-map.mjs'), f);
    assert.ok(lines[2]?.includes('us-atlas 3.0.1'), f);
  }
});
